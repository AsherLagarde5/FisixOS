#!/usr/bin/env python3
"""Embed .deb files into the FisixOS kernel image (build-time install).

Usage: python3 tools/embed_deb.py [deb-file ...]
  With no arguments, embeds every *.deb in OSC/debs/.
  Writes OSC/kernel/drivers/deb_embedded.c (the lookup table) plus
  one OSC/kernel/drivers/deb_embedded_<name>_p<NN>.c file per piece
  of each .deb (same pattern as fse_embedded.c): the .deb bytes
  become static arrays, and deb_install_embedded() installs them
  the first time a `deb` command runs in the terminal.

Why build-time embedding: after ExitBootServices the kernel has no
writable filesystem (FAT driver is read-only, proc file_write
returns -1), so a .deb cannot be loaded from disk at runtime yet.
Baking it into the image is how .fse apps already work, and it is
the honest persistence story until a kernel disk-write driver
lands. See docs/DEB.md.

Why split into pieces: a single deb_embedded.c for these .debs is
~12 MB, too large to push to GitHub in one API request (the
snapshot-push transport rejects it). Each piece holds at most
PART_RAW bytes, so every generated .c file stays small enough to
push. Single-piece .debs are returned directly by
deb_embedded_find(); multi-piece ones are copied once, in order,
into a static buffer the first time they are looked up.
"""
import glob
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OSC = os.path.dirname(HERE)
DRIVERS = os.path.join(OSC, "kernel", "drivers")
OUT = os.path.join(DRIVERS, "deb_embedded.c")
DEBS_DIR = os.path.join(OSC, "debs")

# Raw bytes per piece file. At ~3.6 source chars per byte, 400,000
# raw bytes is ~1.4 MB of C source per file.
PART_RAW = 400000


def c_bytes(data):
    out = []
    for i in range(0, len(data), 16):
        chunk = data[i:i + 16]
        out.append(",".join(str(b) for b in chunk) + ",")
    return "\n".join(out)


def main():
    paths = sys.argv[1:]
    if not paths:
        if os.path.isdir(DEBS_DIR):
            paths = sorted(
                os.path.join(DEBS_DIR, f)
                for f in os.listdir(DEBS_DIR) if f.endswith(".deb"))
    # Remove stale piece files from an earlier run (a .deb that was
    # removed, or one that shrank to fewer pieces, must not leave
    # orphan pieces behind that still get compiled in).
    for stale in glob.glob(os.path.join(DRIVERS, "deb_embedded_*_p[0-9][0-9].c")):
        os.remove(stale)

    entries = []  # (name, total_len, nparts, buf_name or None)
    externs = []
    part_tables = []
    buffers = []
    for p in paths:
        with open(p, "rb") as f:
            data = f.read()
        # C identifier: any character that is not [A-Za-z0-9_]
        # becomes '_'. (The old code only replaced '-', so a
        # real Debian file name such as hello_2.10-5_amd64.deb
        # or libc6_2.36-9+deb12u14_amd64.deb produced an invalid
        # identifier with '.' / '+' in it and the generated file
        # did not compile.)
        base = os.path.splitext(os.path.basename(p))[0]
        name = "".join(c if c.isalnum() or c == "_" else "_" for c in base)
        nparts = max(1, (len(data) + PART_RAW - 1) // PART_RAW)
        for i in range(nparts):
            piece = data[i * PART_RAW:(i + 1) * PART_RAW]
            piece_name = "deb_%s_p%02d" % (name, i)
            with open(os.path.join(DRIVERS, "deb_embedded_%s_p%02d.c" % (name, i)), "w") as f:
                f.write("/* deb_embedded_%s_p%02d.c - piece %d of %d of the embedded %s.\n"
                        % (name, i, i + 1, nparts, os.path.basename(p)))
                f.write(" * GENERATED by tools/embed_deb.py; do not edit by hand.\n")
                f.write(" * See deb_embedded.c for how the pieces are reassembled. */\n")
                f.write('#include <stdint.h>\n\n')
                f.write("const uint8_t %s[] = {\n%s\n};\n" % (piece_name, c_bytes(piece)))
            # Sized extern: sizeof() on it is a compile-time constant,
            # so the part tables below can use it in initializers. (A
            # separate `const uint32_t <name>_len` variable would NOT
            # work there: a const variable is not a constant
            # expression in C.)
            externs.append("extern const uint8_t %s[%d];"
                           % (piece_name, len(piece)))
        part_tables.append(
            "static const struct deb_emb_part deb_%s_parts[] = {\n%s\n};"
            % (name, ",\n".join(
                "    { deb_%s_p%02d, sizeof(deb_%s_p%02d) }" % (name, i, name, i)
                for i in range(nparts))))
        if nparts > 1:
            buffers.append("static uint8_t deb_%s_buf[%d];\nstatic int deb_%s_done = 0;"
                           % (name, len(data), name))
            entries.append((name, len(data), nparts, "deb_%s_buf" % name,
                            "&deb_%s_done" % name))
        else:
            entries.append((name, len(data), nparts, "0", "0"))

    with open(OUT, "w") as f:
        f.write("/* deb_embedded.c - embedded .deb files (GENERATED).\n")
        f.write(" * Generated by tools/embed_deb.py. Do not edit by hand;\n")
        f.write(" * re-run the generator. See docs/DEB.md.\n")
        f.write(" *\n")
        f.write(" * The .deb bytes live in deb_embedded_<name>_p<NN>.c piece\n")
        f.write(" * files (one .deb split into ~%d KB pieces) because a single\n" % (PART_RAW // 1000))
        f.write(" * deb_embedded.c is too large to push to GitHub in one API\n")
        f.write(" * request. Single-piece .debs are returned directly;\n")
        f.write(" * multi-piece ones are copied once, in order, into a static\n")
        f.write(" * buffer the first time deb_embedded_find() is called for them.\n")
        f.write(" */\n")
        f.write('#include "deb_embedded.h"\n\n')
        f.write("struct deb_emb_part { const uint8_t *d; uint32_t l; };\n")
        f.write("struct deb_emb_entry {\n")
        f.write("    const struct deb_emb_part *parts;\n")
        f.write("    uint32_t nparts;\n")
        f.write("    uint32_t total;\n")
        f.write("    uint8_t *buf;   /* NULL when nparts == 1: return the piece directly */\n")
        f.write("    int *done;      /* NULL when nparts == 1 */\n")
        f.write("};\n\n")
        if externs:
            f.write("\n".join(externs))
            f.write("\n\n")
        if part_tables:
            f.write("\n\n".join(part_tables))
            f.write("\n\n")
        if buffers:
            f.write("\n".join(buffers))
            f.write("\n\n")
        f.write("int deb_embedded_find(int idx, const uint8_t **data, "
                "uint32_t *len) {\n")
        if entries:
            f.write("    static const struct deb_emb_entry tbl[] = {\n")
            for (name, total, nparts, buf, done) in entries:
                f.write("        { deb_%s_parts, %d, %d, %s, %s },\n"
                        % (name, nparts, total, buf, done))
            f.write("    };\n")
            f.write("    const struct deb_emb_entry *e;\n")
            f.write("    uint32_t i, j;\n")
            f.write("    uint8_t *dst;\n")
            f.write("    if (!data || !len || idx < 0 || idx >= %d) return 0;\n" % len(entries))
            f.write("    e = &tbl[idx];\n")
            f.write("    if (e->nparts == 1) {\n")
            f.write("        *data = e->parts[0].d;\n")
            f.write("        *len = e->parts[0].l;\n")
            f.write("        return 1;\n")
            f.write("    }\n")
            f.write("    if (!*e->done) {\n")
            f.write("        dst = e->buf;\n")
            f.write("        for (i = 0; i < e->nparts; i++)\n")
            f.write("            for (j = 0; j < e->parts[i].l; j++)\n")
            f.write("                *dst++ = e->parts[i].d[j];\n")
            f.write("        *e->done = 1;\n")
            f.write("    }\n")
            f.write("    *data = e->buf;\n")
            f.write("    *len = e->total;\n")
            f.write("    return 1;\n")
        else:
            f.write("    (void)idx; (void)data; (void)len;\n    return 0;\n")
        f.write("}\n")
    print("embed_deb: %d .deb file(s) -> %s (+ piece files)" % (len(entries), OUT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
