void video_init(void) {
  REG_DISPCNT = 3 | (1 << 10);
  video_clear(0);
}
void video_clear(u16 color) {
  int i;
  for (i = 0; i < SCREEN_W * SCREEN_H; i++) VRAM[i] = color;
}
void video_pixel(int x, int y, u16 color) {
  if (x < 0 || x >= SCREEN_W || y < 0 || y >= SCREEN_H) return;
  VRAM[y * SCREEN_W + x] = color;
}
void video_rect(int x, int y, int w, int h, u16 color) {
  int i, j;
  for (j = 0; j < h; j++)
    for (i = 0; i < w; i++) video_pixel(x + i, y + j, color);
}
void video_wait_vblank(void) {
  while (REG_VCOUNT >= 160) { }
  while (REG_VCOUNT < 160) { }
}
void video_text(int x, int y, const char *s, u16 color) {
  int cx = x;
  while (*s) {
    unsigned char c = (unsigned char)*s++;
    int r, b;
    if (c >= 'a' && c <= 'z') c = (unsigned char)(c - 'a' + 'A');
    if (c < 32 || c > 126) { cx += 8; continue; }
    for (r = 0; r < 8; r++) {
      u8 row = font[c - 32][r];
      for (b = 0; b < 8; b++)
        if (row & (0x80 >> b)) video_pixel(cx + b, y + r, color);
    }
    cx += 8;
    if (cx > SCREEN_W - 8) break;
  }
}
